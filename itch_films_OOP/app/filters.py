def plural_ru(n: int, one: str, few: str, many: str) -> str:
    """
    Возвращает словоформу, согласованную с числом n по правилам
    русского языка.

    one  — форма для 1, 21, 31... (но не 11): "результат"
    few  — форма для 2-4, 22-24... (но не 12-14): "результата"
    many — форма для остальных чисел (0, 5-20, 25-30...): "результатов"

    Используется в шаблонах как фильтр: {{ n | plural_ru('результат', 'результата', 'результатов') }}
    """
    if n % 10 == 1 and n % 100 != 11:
        return one
    if n % 10 in (2, 3, 4) and n % 100 not in (12, 13, 14):
        return few
    return many
